#!/usr/bin/env python3
"""Writes xray_uni.h: the Unicode L and N ranges behind the X-ray grammar's
boundaries, (?<![\\p{L}\\p{N}_]) and (?![\\p{L}\\p{N}_]) (spec #832 v2.1 2.2,
v3.2.1 2.1: dch adds the category tables, QA F1.4).

    python3 scripts/gen-xray-uni.py > xray_uni.h

The table follows this Python's unicodedata version, printed in the header;
regenerate with a newer Python to follow a newer Unicode."""
import sys, unicodedata

rs = []
for c in range(0x110000):
    if unicodedata.category(chr(c))[0] in "LN":
        if rs and rs[-1][1] == c - 1:
            rs[-1][1] = c
        else:
            rs.append([c, c])
print("/* xray_uni.h: generated by scripts/gen-xray-uni.py; do not edit.")
print("** Unicode %s: the L and N general categories, %d ranges. */"
      % (unicodedata.unidata_version, len(rs)))
print("static const uint32_t xr_uni_ln[][2] = {")
for k in range(0, len(rs), 4):
    print("\t" + " ".join("{0x%x, 0x%x}," % (a, b) for a, b in rs[k:k + 4]))
print("};")
